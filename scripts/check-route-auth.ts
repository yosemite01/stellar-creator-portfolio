#!/usr/bin/env tsx
/**
 * CI guard: every `route.ts` file under `app/api/` must declare its auth mode.
 *
 * Accepted declarations:
 *   - `export const auth = 'public' | 'session' | 'admin' | 'cron' | 'webhook'`
 *   - use of the `route({ auth: ... })` wrapper from `lib/auth/route`
 *
 * Generated / third-party handlers are allowlisted below with a comment.
 *
 * Run: `pnpm tsx scripts/check-route-auth.ts`
 */
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = process.cwd();
const API_DIR = join(ROOT, 'app', 'api');
const CONTRIBUTING_URL =
  'https://github.com/yosemite01/stellar-creator-portfolio/blob/main/CONTRIBUTING.md#route-auth';

const ALLOWED_AUTH_VALUES = ['public', 'session', 'admin', 'cron', 'webhook'] as const;

/**
 * Generated / third-party handlers that do not own their auth surface.
 * Keep this list tiny and justified — each entry needs a reason.
 */
const ALLOWLIST: ReadonlyArray<{ pattern: RegExp; reason: string }> = [
  // NextAuth owns its own session handling; the handler is generated by the library.
  { pattern: /app\/api\/auth\/\[\.\.\.nextauth\]\/route\.ts$/, reason: 'NextAuth generated handler' },
  // tRPC router owns auth per-procedure; the HTTP handler is a thin adapter.
  { pattern: /app\/api\/trpc\/\[\.\.\.trpc\]\/route\.ts$/, reason: 'tRPC adapter' },
];

function isAllowlisted(relPath: string): boolean {
  return ALLOWLIST.some((entry) => entry.pattern.test(relPath));
}

function walk(dir: string, out: string[] = []): string[] {
  let entries: string[];
  try {
    entries = readdirSync(dir);
  } catch {
    return out;
  }
  for (const entry of entries) {
    const full = join(dir, entry);
    const stat = statSync(full);
    if (stat.isDirectory()) {
      walk(full, out);
    } else if (entry === 'route.ts') {
      out.push(full);
    }
  }
  return out;
}

const EXPORT_AUTH_RE = /export\s+const\s+auth\s*=\s*['"]([a-z]+)['"]/;
const ROUTE_WRAPPER_RE = /\broute\s*\(\s*\{[^}]*\bauth\s*:/s;

function declaresAuth(source: string): { ok: boolean; reason?: string } {
  const exportMatch = source.match(EXPORT_AUTH_RE);
  if (exportMatch) {
    const value = exportMatch[1];
    if ((ALLOWED_AUTH_VALUES as readonly string[]).includes(value)) {
      return { ok: true };
    }
    return {
      ok: false,
      reason: `invalid auth value '${value}' (allowed: ${ALLOWED_AUTH_VALUES.join(', ')})`,
    };
  }
  if (ROUTE_WRAPPER_RE.test(source)) {
    return { ok: true };
  }
  return { ok: false, reason: 'no `export const auth = ...` and no `route({ auth: ... })` wrapper' };
}

function main(): void {
  const files = walk(API_DIR);
  const offenders: Array<{ file: string; reason: string }> = [];

  for (const file of files) {
    const relPath = relative(ROOT, file).split('\\').join('/');
    if (isAllowlisted(relPath)) continue;
    const source = readFileSync(file, 'utf8');
    const result = declaresAuth(source);
    if (!result.ok) {
      offenders.push({ file: relPath, reason: result.reason ?? 'missing auth declaration' });
    }
  }

  if (offenders.length > 0) {
    console.error('\n✖ Route auth check failed.\n');
    console.error('Every `app/api/**/route.ts` must declare its auth mode.\n');
    console.error('Accepted forms:');
    console.error("  export const auth = 'public' | 'session' | 'admin' | 'cron' | 'webhook'");
    console.error('  // or use the route({ auth: ... }) wrapper from lib/auth/route\n');
    console.error('Offending files:');
    for (const { file, reason } of offenders) {
      console.error(`  - ${file}  (${reason})`);
    }
    console.error(`\nSee ${CONTRIBUTING_URL} for details.\n`);
    process.exit(1);
  }

  console.log(`✔ Route auth check passed (${files.length} route file(s) scanned).`);
}

main();
